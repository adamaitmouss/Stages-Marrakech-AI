import sys
import os
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.common import prepare
import os
import pandas as pd
import matplotlib.pyplot as plt

def main():
    prepare(external=False)
    os.makedirs('reports/graphs', exist_ok=True)
    df_entreprises = pd.read_excel('data_clean/entreprises_marrakech_clean.xlsx')
    df_offres = pd.read_excel('data_clean/offres_stagiaires_marrakech_clean.xlsx')
    secteurs = df_entreprises['Secteur'].value_counts()
    plt.figure(figsize=(10, 6))
    secteurs.plot(kind='bar')
    plt.title('Entreprises par secteur')
    plt.ylabel('Nombre')
    plt.tight_layout()
    plt.savefig('reports/graphs/secteurs_barplot.png')
    plt.close()
    plt.figure(figsize=(8, 8))
    secteurs.plot(kind='pie', autopct='%1.1f%%')
    plt.ylabel('')
    plt.title('Répartition des secteurs')
    plt.tight_layout()
    plt.savefig('reports/graphs/secteurs_pie.png')
    plt.close()
    types_stage = df_offres['Type stage'].fillna('Non renseigné').value_counts()
    plt.figure(figsize=(8, 5))
    types_stage.plot(kind='bar')
    plt.title('Offres par type de stage')
    plt.ylabel('Nombre')
    plt.tight_layout()
    plt.savefig('reports/graphs/types_stage.png')
    plt.close()
    plt.figure(figsize=(8, 8))
    types_stage.plot(kind='pie', autopct='%1.1f%%')
    plt.ylabel('')
    plt.title('Répartition des types de stage')
    plt.tight_layout()
    plt.savefig('reports/graphs/types_stage_pie.png')
    plt.close()
    types_contrat = df_offres['Type contrat'].value_counts()
    plt.figure(figsize=(8, 5))
    types_contrat.plot(kind='bar')
    plt.title('Offres par type de contrat')
    plt.ylabel('Nombre')
    plt.tight_layout()
    plt.savefig('reports/graphs/types_contrat.png')
    plt.close()
    plt.figure(figsize=(8, 8))
    types_contrat.plot(kind='pie', autopct='%1.1f%%')
    plt.ylabel('')
    plt.title('Répartition des contrats')
    plt.tight_layout()
    plt.savefig('reports/graphs/types_contrat_pie.png')
    plt.close()
    avec_email = df_entreprises['Emails'].notna().sum()
    sans_email = df_entreprises['Emails'].isna().sum()
    plt.figure(figsize=(6, 6))
    plt.pie([avec_email, sans_email], labels=['Avec Email', 'Sans Email'], autopct='%1.1f%%')
    plt.title('Présence des emails')
    plt.savefig('reports/graphs/emails.png')
    plt.close()
    avec_site = df_entreprises['Site Web'].notna().sum()
    sans_site = df_entreprises['Site Web'].isna().sum()
    plt.figure(figsize=(6, 6))
    plt.pie([avec_site, sans_site], labels=['Avec Site', 'Sans Site'], autopct='%1.1f%%')
    plt.title('Présence des sites web')
    plt.savefig('reports/graphs/sites_web.png')
    plt.close()
    df_offres['Date publication'] = pd.to_datetime(df_offres['Date publication'])
    offres_dates = df_offres['Date publication'].dt.date.value_counts().sort_index()
    plt.figure(figsize=(12, 5))
    plt.plot(offres_dates.index, offres_dates.values, marker='o')
    plt.title('Evolution des offres')
    plt.ylabel('Nombre')
    plt.xticks(rotation=45)
    plt.tight_layout()
    plt.savefig('reports/graphs/offres_dates.png')
    plt.close()
    print('\n=================================')
    print('GRAPHIQUES CREES')
    print('=================================')
    print('✓ secteurs_barplot.png')
    print('✓ secteurs_pie.png')
    print('✓ types_stage.png')
    print('✓ types_stage_pie.png')
    print('✓ types_contrat.png')
    print('✓ types_contrat_pie.png')
    print('✓ emails.png')
    print('✓ sites_web.png')
    print('✓ offres_dates.png')
    print('\nDossier : reports/graphs/')

if __name__ == "__main__":
    main()
